import assert from 'node:assert/strict';
import { stepGuidance, guidanceAligned } from '../src/domain/manual-guidance.js';
import { MANUAL_GUIDANCE } from '../src/content/manual-guidance.js';
const tune = MANUAL_GUIDANCE.quiver, cone = Math.tan(9 * Math.PI / 180), tol = Math.tan(tune.toleranceDeg * Math.PI / 180);
const sight = { x: tune.start[0], y: tune.start[1] };
assert(!guidanceAligned(0, 0, sight, cone, tol), 'mouse alone cannot lock a centred target');
assert(!guidanceAligned(sight.x*cone,-sight.y*cone,sight,cone,tol),'mouse cannot bypass the primary sight by aiming only at the secondary');
stepGuidance(sight, { left: true }, tune.start[0] / tune.speed, tune);
stepGuidance(sight, { down: true }, -tune.start[1] / tune.speed, tune);
assert(guidanceAligned(0, 0, sight, cone, tol));
assert(!guidanceAligned(cone * 0.8, 0, sight, cone, tol), 'moving target breaks secondary alignment');
assert(!guidanceAligned(cone * 1.1, 0, { x: 1, y: 0 }, cone, tol), 'secondary cannot acquire outside primary sight');
stepGuidance(sight, { right: true, down: true }, 100, tune);
assert.deepEqual(sight, { x: 1, y: 1, vx: 0, vy: 0 });
const a = { x: 0, y: 0 }, b = { x: 0, y: 0 };
stepGuidance(a, { up: true }, 0.5, tune);
for (let i = 0; i < 60; i++) stepGuidance(b, { up: true }, 0.5 / 60, tune);
assert(Math.abs(a.y - b.y) < 1e-9, 'frame-rate independent');
console.log('manual-guidance: two sights, target loss, bounds, frame-rate independent');

const coast = { x: 0, y: 0 };
stepGuidance(coast, { right: true }, .1, tune);
assert(coast.vx > 0 && coast.vx < tune.speed, 'accelerates instead of starting at full speed');
const before = coast.x, velocity = coast.vx;
stepGuidance(coast, {}, .1, tune);
assert(coast.x > before && coast.vx < velocity && coast.vx > 0, 'continues moving while slowing after release');
stepGuidance(coast, { left: true }, .01, tune);
assert(coast.vx > 0, 'reversing first brakes the existing momentum');
stepGuidance(coast, {}, 3, tune); assert(coast.vx < .00001, 'settles without perpetual drift');
