import assert from 'node:assert/strict';
import { accessSync } from 'node:fs';
import * as THREE from '../vendor/three.module.js';
import { MINERALS as M } from '../src/content/minerals.js';
import { pickDeposits, takeMineral, surfaceArc } from '../src/domain/mineral-deposits.js';
import { createRoverRun, dispatch, stepRover } from '../src/domain/rover-run.js';
import { createAmethyst } from '../src/fx/crystals.js';
import { createScoutSpecimens } from '../src/fx/scout-specimens.js';
accessSync(new URL('../'+M.model,import.meta.url));
const centers=Array.from({length:100},(_,i)=>[Math.sin(i*.01),Math.cos(i*.01),0]), candidates=centers.map((_,i)=>i).slice(10);
const deposits=pickDeposits(candidates,centers,54,M,.001);
assert.deepEqual(deposits,pickDeposits([...candidates].reverse(),centers,54,M,.001));
assert.notDeepEqual(deposits,pickDeposits(candidates,centers,55,M,.001));
assert.equal(deposits.length,M.count);
for(const a of deposits)for(const b of deposits)if(a!==b)assert.ok(surfaceArc(centers[a.cell],centers[b.cell])>=M.separationM*.001);
const run=createRoverRun(M,0);let bank=0,space=0;
const host={path:(a,b)=>[a,b],length:()=>40,bearing:()=>0,live:o=>deposits.some(d=>d.id===o?.id&&d.kg>0),near:cell=>deposits.filter(d=>d.cell===cell&&d.kg>0),take:(c,n)=>takeMineral(deposits,c,n),deposit:n=>{const v=Math.min(space-bank,n);bank+=v;return v;}};
dispatch(run,deposits[0]);
for(let t=0;t<20;t+=.1)stepRover(run,.1,t,host);
assert.equal(run.mode,'full');assert.equal(bank,0);assert.equal(run.cargo,M.capacity);
space=10000;
for(let t=20;t<180;t+=.1)stepRover(run,.1,t,host);
assert.equal(bank,M.kg);assert.equal(run.cargo,0);assert.equal(deposits[0].kg,0);assert.equal(run.mode,'idle');
assert.equal(deposits.reduce((n,d)=>n+d.kg,0)+bank,M.count*M.kg);
const cluster=createAmethyst(8);assert.equal(cluster.meshes.length,9);
for(const mesh of cluster.meshes){assert.ok(mesh.geometry.attributes.position.count>0);assert.ok(mesh.geometry.userData.planes.length<=40);mesh.updateMatrixWorld();mesh.onBeforeRender();}
cluster.dispose();
const scene=new THREE.Scene(), specimens=createScoutSpecimens(scene,[{kind:'rock',cell:1,point:[0,1,0]},{kind:'biomass',cell:2,point:[.01,1,0]}],.001);
for(let i=0;i<20;i++)specimens.tick(.05,i*.05,new THREE.PerspectiveCamera());
assert.deepEqual(specimens.state().map(o=>[o.kind,o.alive,o.damage]),[['amethyst',false,0],['harmless Cutis',true,0]]);
specimens.dispose();assert.equal(scene.children.length,0);
console.log('Minerals: seeded spaced deposits, finite harvest, storage hold, home delivery; crystal and harmless Cutis lifecycle.');
