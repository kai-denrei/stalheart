// import-isao-voice.mjs — Isao's voice lines from the seiyu_voice hand-off into the game (owner, 2026-10-03: "154 candidate voice tracks
// to give life to Isao ... let's wire them"). Reads the export's manifest.json and isao/<id>.wav, encodes each line to a mono 64 kbps
// MP3 at its own 24 kHz (assets/audio/isao/<id>.mp3), and writes the generated table src/content/isao-voice.js and the pin
// docs/isao-voice-audio.lock.json. The export is the source of truth for text, ids, kinds and beats; re-run after every new drop.
// Usage: node scripts/import-isao-voice.mjs [path to the seiyu_voice export]   (default ../seiyu_voice/export)
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const from = resolve(process.argv[2] ?? resolve(root, '../seiyu_voice/export'));
const manifest = JSON.parse(readFileSync(resolve(from, 'manifest.json'), 'utf8'));
if (manifest.voice !== 'isao' || !manifest.triggers) throw Error('Not an Isao voice manifest: ' + from);
const outDir = resolve(root, 'assets/audio/isao');
mkdirSync(outDir, { recursive: true });
const sha = (b) => createHash('sha256').update(b).digest('hex');
const ID = /^[a-z0-9_]+_\d\d$/;

const triggers = {}, files = [], keep = new Set();
for (const [key, t] of Object.entries(manifest.triggers)) {
  const lines = [];
  for (const l of t.lines) {
    if (!ID.test(l.id)) throw Error('Unexpected line id ' + l.id);
    const wav = resolve(from, l.file), mp3 = `assets/audio/isao/${l.id}.mp3`;
    execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-i', wav, '-ac', '1', '-b:a', '64k', '-map_metadata', '-1', '-fflags', '+bitexact', '-flags:a', '+bitexact', resolve(root, mp3)]);
    const bytes = readFileSync(resolve(root, mp3));
    files.push({ path: mp3, id: l.id, sha256: sha(bytes), bytes: bytes.length, sourceSha256: sha(readFileSync(wav)) });
    keep.add(`${l.id}.mp3`);
    lines.push({ id: l.id, text: l.text, kind: l.kind, duration: l.duration_s, ...(l.qualifier ? { qualifier: l.qualifier } : {}), ...(l.beats ? { beats: l.beats } : {}) });
  }
  triggers[key] = { aliases: t.aliases, ...(t.note ? { note: t.note } : {}), lines };
}
// a line dropped from the script leaves the game with it
for (const f of readdirSync(outDir)) if (f.endsWith('.mp3') && !keep.has(f)) rmSync(resolve(outDir, f));

const n = files.length;
writeFileSync(resolve(root, 'src/content/isao-voice.js'), `// GENERATED by scripts/import-isao-voice.mjs from the seiyu_voice export (${manifest.chain_version}, ${manifest.generated}); do not edit.
// Isao's recorded lines by trigger: ${Object.keys(triggers).length} triggers, ${n} lines. Files are assets/audio/isao/<id>.mp3, pinned in
// docs/isao-voice-audio.lock.json. \`kind\` is spoken, announce or countdown; \`beats\` are a countdown's number onsets in seconds from
// the file's start; \`qualifier\` is a game-side condition that is never spoken.
export const ISAO_VOICE_SOURCE = Object.freeze({ chain: ${JSON.stringify(manifest.chain_version)}, generated: ${JSON.stringify(manifest.generated)} });
export const ISAO_TRIGGERS = ${JSON.stringify(triggers, null, 1)};
`);
writeFileSync(resolve(root, 'docs/isao-voice-audio.lock.json'), JSON.stringify({ schema: 2, source: `seiyu_voice export ${manifest.chain_version} ${manifest.generated}: 24 kHz mono WAV, encoded by scripts/import-isao-voice.mjs to mono 64 kbps MP3, no normalisation`, files }, null, 1) + '\n');
console.log(`Isao voice: ${n} lines in ${Object.keys(triggers).length} triggers -> assets/audio/isao (${(files.reduce((a, f) => a + f.bytes, 0) / 1e6).toFixed(1)} MB)`);
if (!existsSync(resolve(root, 'assets/audio/isao'))) throw Error('no output');
